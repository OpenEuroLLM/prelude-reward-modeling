def rules_for(source, subset, meta):
    r = dict(DEFAULTS)
    r.update(SOURCES[source])
    for s, pat, over in _COMPILED:
        if s == source and pat.search(subset or ""):
            r.update(over)
    # --- record-level rules
    if source == "facebook/community-alignment-dataset":
        if (meta.get("turn") or 1) > 1:
            r["exclude"] = "uncertain_history_turn_gt1"
        elif meta.get("is_pregenerated_first_prompt"):
            r["origin"] = "synthetic"
    if source == "OpenAssistant/oasst2":
        if meta.get("deleted") or meta.get("review_result") is False \
                or meta.get("context_deleted") or meta.get("context_review_failed"):
            r["exclude"] = "oasst_deleted_or_review_failed"
    return r


def resolve_translated(rule, lang):
    t = rule["translated"]
    if t == "all":
        return True
    if t == "non_en":
        return lang != "en"
    if t == "non_pl":
        return lang != "pl"
    return False


