def norm_lang(label):
    """Map a source-provided language label to our code (or None)."""
    if label is None:
        return None
    s = str(label).strip()
    if not s:
        return None
    low = s.lower()
    if low in NAMES:
        return NAMES[low]
    base = re.split(r"[-_]", low)[0]
    if base in ISO1_EXTRA:
        return ISO1_EXTRA[base]
    if len(base) == 2:
        return base
    if base in ISO3:
        return ISO3[base]
    return None


# Language groups that LID often confuses; a trusted source label inside the
# same group overrides the LID decision.
CONFUSABLE = [{"bs", "hr", "sr", "mk"}, {"nb", "nn", "da", "sv"}, {"cs", "sk"},
              {"es", "ca", "gl", "pt"}, {"lv", "ltg"}, {"sq"}, {"et", "fi"}]


def confusable(a, b):
    return any(a in g and b in g for g in CONFUSABLE)
